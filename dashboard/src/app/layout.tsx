import type { Metadata } from "next";
import Link from "next/link";
import "./globals.css";
import { createClient } from "@/lib/supabase/server";

export const metadata: Metadata = {
  title: "Intraday Picks",
  description: "Daily NSE intraday watchlist, confirmations and scorecard",
};

export const dynamic = "force-dynamic";

export default async function RootLayout({ children }: { children: React.ReactNode }) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  return (
    <html lang="en">
      <body className="min-h-screen">
        {user && (
          <header className="border-b" style={{ borderColor: "var(--border)", background: "var(--surface-1)" }}>
            <div className="mx-auto flex max-w-6xl flex-wrap items-center gap-2 px-4 py-3">
              <Link href="/" className="mr-4 font-semibold">Intraday Picks</Link>
              <nav className="flex gap-1 text-sm">
                <Link className="nav-link" href="/">Today</Link>
                <Link className="nav-link" href="/history">History</Link>
                <Link className="nav-link" href="/market">Market</Link>
                <Link className="nav-link" href="/watchlist">Watchlist</Link>
                <Link className="nav-link" href="/focus">Your list</Link>
              </nav>
              <form action="/auth/signout" method="post" className="ml-auto flex items-center gap-3 text-sm">
                <span className="muted hidden sm:inline">{user.email}</span>
                <button className="btn" type="submit">Sign out</button>
              </form>
            </div>
          </header>
        )}
        <main className="mx-auto max-w-6xl px-4 py-6">{children}</main>
        <footer className="mx-auto max-w-6xl px-4 pb-8 text-xs muted">
          Not financial advice. Picks are generated by rules; you decide. Paper-trade before risking money.
        </footer>
      </body>
    </html>
  );
}
